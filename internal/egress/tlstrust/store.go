package tlstrust

import (
	"bytes"
	"crypto/sha256"
	"crypto/tls"
	"encoding/binary"
	"encoding/hex"
	"encoding/json"
	"errors"
	"io"
	"io/fs"
	"math"
	"sync"
	"time"
)

// MaxOverlap bounds how long an old and a staged trust set may both be valid.
const MaxOverlap = 24 * time.Hour

// Action names an audited trust decision.
type Action string

const (
	Approval    Action = "approval"
	Rotation    Action = "rotation"
	Replacement Action = "replacement"
	PinMismatch Action = "pin-mismatch"
)

// AuditEvent describes a trust decision. It deliberately carries no
// certificate material and no error text.
type AuditEvent struct {
	At      time.Time
	Origin  Origin
	Action  Action
	Allowed bool
}

var (
	ErrUnapproved = errors.New("tlstrust: origin has no approved trust")
	ErrStore      = errors.New("tlstrust: trust store failure")
	ErrAudit      = errors.New("tlstrust: audit failure")
)

const (
	recordVersion = 1
	// maxRecordSize bounds every record read from or written to disk.
	maxRecordSize = 512 << 10
	recordSuffix  = ".rec"
)

// backend is the platform persistence seam. Names are flat record file names
// generated by this package. Implementations must return fs.ErrNotExist for
// missing records and wrap ambiguous commits in commitError.
type backend interface {
	read(name string) ([]byte, error)
	write(name string, data []byte) error
	close() error
}

// commitError marks a write whose on-disk outcome is unknown.
type commitError struct{ err error }

func (e *commitError) Error() string { return "tlstrust: ambiguous commit: " + e.err.Error() }
func (e *commitError) Unwrap() error { return e.err }

// Store persists approved trust per exact origin.
type Store struct {
	mu       sync.Mutex
	be       backend
	closed   bool
	poisoned bool
	now      func() time.Time

	auditMu sync.Mutex
	audit   func(AuditEvent) error
}

// Open opens the private trust directory dir. audit is required and is
// invoked on trusted administrative paths before any decision is published.
func Open(dir string, audit func(AuditEvent) error) (*Store, error) {
	if audit == nil {
		return nil, ErrAudit
	}
	be, err := openBackend(dir)
	if err != nil {
		return nil, err
	}
	return &Store{be: be, audit: audit, now: time.Now}, nil
}

// Close releases the directory lock. It is idempotent.
func (s *Store) Close() error {
	if s == nil {
		return ErrStore
	}
	s.mu.Lock()
	defer s.mu.Unlock()
	if s.closed {
		return nil
	}
	if s.be == nil {
		return ErrStore
	}
	s.closed = true
	if err := s.be.close(); err != nil {
		return ErrStore
	}
	return nil
}

// Approve records first-time trust for o after out-of-band verification.
func (s *Store) Approve(o Origin, c Candidate, outOfBand []Pin) error {
	if s == nil {
		return ErrStore
	}
	s.mu.Lock()
	defer s.mu.Unlock()
	if err := s.usable(); err != nil {
		return err
	}
	if !validateOrigin(o) {
		return ErrInvalid
	}
	_, err := s.load(o)
	switch {
	case err == nil:
		return ErrInvalid // existing policy changes only via rotation
	case !errors.Is(err, ErrUnapproved):
		return err
	}
	now := s.now()
	if err := validateCandidate(o, c, outOfBand, now); err != nil {
		return s.denied(o, Approval, err)
	}
	rec := &record{origin: o, active: cloneCandidate(c)}
	return s.commit(o, Approval, rec)
}

// BeginRotation stages c next to the active trust for at most overlap.
func (s *Store) BeginRotation(o Origin, c Candidate, outOfBand []Pin, overlap time.Duration) error {
	if s == nil {
		return ErrStore
	}
	s.mu.Lock()
	defer s.mu.Unlock()
	if err := s.usable(); err != nil {
		return err
	}
	if !validateOrigin(o) || overlap <= 0 || overlap > MaxOverlap {
		return ErrInvalid
	}
	rec, err := s.load(o)
	if err != nil {
		return err
	}
	if rec.staged != nil { // no chained overlap before explicit Replace
		return ErrInvalid
	}
	if !sameShape(rec.active, c) {
		return ErrInvalid
	}
	now := s.now()
	started := now.UnixNano()
	if started <= 0 || started > math.MaxInt64-int64(overlap) {
		return ErrInvalid
	}
	if err := validateCandidate(o, c, outOfBand, now); err != nil {
		return s.denied(o, Rotation, err)
	}
	staged := cloneCandidate(c)
	next := &record{
		origin:   o,
		active:   rec.active,
		staged:   &staged,
		started:  started,
		deadline: started + int64(overlap),
	}
	return s.commit(o, Rotation, next)
}

// Replace promotes the already-approved staged trust, early or after overlap.
func (s *Store) Replace(o Origin) error {
	if s == nil {
		return ErrStore
	}
	s.mu.Lock()
	defer s.mu.Unlock()
	if err := s.usable(); err != nil {
		return err
	}
	if !validateOrigin(o) {
		return ErrInvalid
	}
	rec, err := s.load(o)
	if err != nil {
		return err
	}
	if rec.staged == nil {
		return ErrInvalid
	}
	return s.commit(o, Replacement, &record{origin: o, active: *rec.staged})
}

// Bind returns a binding for o. Binding an unapproved origin succeeds; its
// handshakes then fail closed.
func (s *Store) Bind(o Origin) *Binding {
	return &Binding{store: s, origin: o}
}

// Binding is the opaque, store-approved TLS policy for one origin.
type Binding struct {
	store  *Store
	origin Origin
}

// Matches reports whether the binding was created for exactly o.
func (b *Binding) Matches(o Origin) bool {
	return b != nil && b.store != nil && validateOrigin(o) && b.origin == o
}

// TLSConfig loads the current record from disk and returns a verifying
// configuration. Missing, mismatched or corrupt state fails closed; it never
// falls back to public roots. Call it for every connection attempt.
func (b *Binding) TLSConfig() (*tls.Config, error) {
	if b == nil || b.store == nil {
		return nil, ErrStore
	}
	s := b.store
	s.mu.Lock()
	if err := s.usable(); err != nil {
		s.mu.Unlock()
		return nil, err
	}
	if !validateOrigin(b.origin) {
		s.mu.Unlock()
		return nil, ErrInvalid
	}
	rec, err := s.load(b.origin)
	s.mu.Unlock()
	if err != nil {
		return nil, err
	}
	var staged *Candidate
	var deadline time.Time
	if rec.staged != nil {
		staged = rec.staged
		deadline = time.Unix(0, rec.deadline)
	}
	o := b.origin
	return configFor(o, rec.active, staged, deadline, s.now, func() error {
		return s.emit(AuditEvent{At: s.now().UTC(), Origin: o, Action: PinMismatch, Allowed: false})
	})
}

// usable must be called with s.mu held.
func (s *Store) usable() error {
	if s.be == nil || s.audit == nil || s.now == nil || s.closed || s.poisoned {
		return ErrStore
	}
	return nil
}

func (s *Store) emit(ev AuditEvent) error {
	s.auditMu.Lock()
	defer s.auditMu.Unlock()
	if err := s.audit(ev); err != nil {
		return ErrAudit
	}
	return nil
}

// denied audits a rejected administrative decision as a denied attempt of the
// supplied action (never as a PinMismatch, which is an integration-side
// handshake event) and returns the original failure. If the audit fails both
// ErrAudit and the original sentinel are reported.
func (s *Store) denied(o Origin, a Action, cause error) error {
	orig := ErrInvalid
	if errors.Is(cause, ErrPinMismatch) {
		orig = ErrPinMismatch
	}
	if err := s.emit(AuditEvent{At: s.now().UTC(), Origin: o, Action: a, Allowed: false}); err != nil {
		return errors.Join(err, orig)
	}
	return orig
}

// commit records intent durably-before-publication: audit first, then the
// atomic write. s.mu must be held.
func (s *Store) commit(o Origin, a Action, rec *record) error {
	data, err := encodeRecord(rec)
	if err != nil {
		return err
	}
	if err := s.emit(AuditEvent{At: s.now().UTC(), Origin: o, Action: a, Allowed: true}); err != nil {
		return err
	}
	if err := s.be.write(recordName(o), data); err != nil {
		var ce *commitError
		if errors.As(err, &ce) {
			s.poisoned = true
		}
		return ErrStore
	}
	return nil
}

func (s *Store) load(o Origin) (*record, error) {
	data, err := s.be.read(recordName(o))
	if err != nil {
		if errors.Is(err, fs.ErrNotExist) {
			return nil, ErrUnapproved
		}
		return nil, ErrStore
	}
	rec, err := decodeRecord(o, data)
	if err != nil {
		return nil, ErrStore
	}
	return rec, nil
}

// sameShape enforces mode equality and optional-pin presence so rotation can
// never downgrade policy.
func sameShape(active, next Candidate) bool {
	if active.Mode != next.Mode {
		return false
	}
	if active.Mode == PrivateCA {
		return (active.LeafPin == Pin{}) == (next.LeafPin == Pin{})
	}
	return true
}

func cloneCandidate(c Candidate) Candidate {
	out := Candidate{Mode: c.Mode, LeafPin: c.LeafPin, Certificates: make([][]byte, len(c.Certificates))}
	for i, der := range c.Certificates {
		out.Certificates[i] = append([]byte(nil), der...)
	}
	return out
}

func recordName(o Origin) string {
	h := sha256.New()
	h.Write([]byte(o.Scheme))
	h.Write([]byte{0})
	h.Write([]byte(o.Host))
	h.Write([]byte{0})
	h.Write(binary.BigEndian.AppendUint16(nil, o.Port))
	return hex.EncodeToString(h.Sum(nil)) + recordSuffix
}

type record struct {
	origin   Origin
	active   Candidate
	staged   *Candidate
	started  int64 // unix nanos rotation began; nonzero iff staged != nil
	deadline int64 // unix nanos overlap ends; started < deadline <= started+MaxOverlap
}

type originJSON struct {
	Scheme string `json:"scheme"`
	Host   string `json:"host"`
	Port   uint16 `json:"port"`
}

type candidateJSON struct {
	Mode         string   `json:"mode"`
	Certificates [][]byte `json:"certificates"`
	LeafPin      string   `json:"leaf_pin,omitempty"`
}

type recordJSON struct {
	Version  int            `json:"version"`
	Origin   originJSON     `json:"origin"`
	Active   candidateJSON  `json:"active"`
	Staged   *candidateJSON `json:"staged,omitempty"`
	Started  int64          `json:"started_unix_nano,omitempty"`
	Deadline int64          `json:"deadline_unix_nano,omitempty"`
}

func toJSON(c Candidate) candidateJSON {
	j := candidateJSON{Mode: string(c.Mode), Certificates: c.Certificates}
	if c.LeafPin != (Pin{}) {
		j.LeafPin = hex.EncodeToString(c.LeafPin[:])
	}
	return j
}

func fromJSON(j candidateJSON) (Candidate, error) {
	c := Candidate{Mode: Mode(j.Mode), Certificates: j.Certificates}
	if j.LeafPin != "" {
		raw, err := hex.DecodeString(j.LeafPin)
		if err != nil || len(raw) != len(c.LeafPin) {
			return Candidate{}, ErrStore
		}
		copy(c.LeafPin[:], raw)
		if c.LeafPin == (Pin{}) {
			return Candidate{}, ErrStore // zero pin must be omitted
		}
	}
	return c, nil
}

func marshalRecord(rec *record) ([]byte, error) {
	j := recordJSON{
		Version:  recordVersion,
		Origin:   originJSON{rec.origin.Scheme, rec.origin.Host, rec.origin.Port},
		Active:   toJSON(rec.active),
		Started:  rec.started,
		Deadline: rec.deadline,
	}
	if rec.staged != nil {
		s := toJSON(*rec.staged)
		j.Staged = &s
	}
	return json.Marshal(j)
}

func encodeRecord(rec *record) ([]byte, error) {
	data, err := marshalRecord(rec)
	if err != nil || len(data) > maxRecordSize {
		return nil, ErrInvalid
	}
	return data, nil
}

// decodeRecord strictly parses data: bounded, versioned, no unknown fields,
// canonical bytes only, and every certificate re-validated.
func decodeRecord(o Origin, data []byte) (*record, error) {
	if len(data) == 0 || len(data) > maxRecordSize {
		return nil, ErrStore
	}
	dec := json.NewDecoder(bytes.NewReader(data))
	dec.DisallowUnknownFields()
	var j recordJSON
	if err := dec.Decode(&j); err != nil {
		return nil, ErrStore
	}
	if _, err := dec.Token(); err != io.EOF {
		return nil, ErrStore
	}
	if j.Version != recordVersion {
		return nil, ErrStore
	}
	got := Origin{Scheme: j.Origin.Scheme, Host: j.Origin.Host, Port: j.Origin.Port}
	if got != o || !validateOrigin(got) {
		return nil, ErrStore
	}
	active, err := fromJSON(j.Active)
	if err != nil {
		return nil, err
	}
	rec := &record{origin: got, active: active, started: j.Started, deadline: j.Deadline}
	if (j.Staged == nil) != (j.Deadline == 0) || (j.Staged == nil) != (j.Started == 0) {
		return nil, ErrStore
	}
	if j.Staged != nil && (j.Started <= 0 || j.Deadline <= j.Started || j.Deadline-j.Started > int64(MaxOverlap)) {
		return nil, ErrStore
	}
	if validateMaterial(got, active) != nil {
		return nil, ErrStore
	}
	if j.Staged != nil {
		staged, err := fromJSON(*j.Staged)
		if err != nil {
			return nil, err
		}
		if !sameShape(active, staged) || validateMaterial(got, staged) != nil {
			return nil, ErrStore
		}
		rec.staged = &staged
	}
	canon, err := marshalRecord(rec)
	if err != nil || !bytes.Equal(canon, data) {
		return nil, ErrStore
	}
	return rec, nil
}
